	static bool matches ( const wchar_t* prototype, const wchar_t* name, int32_t length ) {

		int32_t open = 0;

		while ( prototype [ open ] && prototype [ open ] != L'(' )
			open++;

		if ( !prototype [ open ] || open < length )
			return false;

		int32_t start = open - length;

		if ( start > 0 ) {

			wchar_t before = prototype [ start - 1 ];

			if ( before != L' ' && before != L'*' )
				return false;

		}

		for ( int32_t i = 0; i < length; i++ ) {

			if ( prototype [ start + i ] != name [ i ] )
				return false;

		}

		return true;

	}

	const wchar_t* api_prototype ( const wchar_t* name ) {

		if ( !name || !name [ 0 ] )
			return nullptr;

		for ( const wchar_t* at = name; *at; at++ ) {

			if ( *at == L'!' )
				name = at + 1;

		}

		static const wchar_t* const prefixes [ ] = { L"__imp_", L"_imp_", L"imp_", L"j_" };

		for ( const wchar_t* prefix : prefixes ) {

			int32_t k = 0;

			while ( prefix [ k ] && prefix [ k ] == name [ k ] )
				k++;

			if ( !prefix [ k ] ) {

				name += k;

				break;

			}

		}

		int32_t length = 0;

		while ( name [ length ] && name [ length ] != L'@' )
			length++;

		if ( !length )
			return nullptr;

		for ( const wchar_t* prototype : api_table ) {

			if ( matches ( prototype, name, length ) )
				return prototype;

		}

		return nullptr;

	}

	int32_t import_arguments ( const wchar_t* name ) {

		const wchar_t* prototype = api_prototype ( name );

		if ( !prototype )
			return -1;

		const wchar_t* at = prototype;

		while ( *at && *at != L'(' )
			at++;

		if ( !*at )
			return -1;

		at++;

		int32_t count = 0;
		int32_t depth = 0;
		const wchar_t* piece = at;

		for ( ; *at; at++ ) {

			wchar_t c = *at;

			if ( c == L'(' )
				depth++;
			else if ( c == L')' && depth > 0 )
				depth--;
			else if ( ( c == L',' || c == L')' ) && depth == 0 ) {

				int32_t from = 0;
				int32_t to = static_cast < int32_t > ( at - piece );

				while ( from < to && piece [ from ] == L' ' )
					from++;

				while ( to > from && piece [ to - 1 ] == L' ' )
					to--;

				bool dots = to - from == 3 && piece [ from ] == L'.';
				bool lone_void = to - from == 4 && piece [ from ] == L'v' && piece [ from + 1 ] == L'o' && piece [ from + 2 ] == L'i' && piece [ from + 3 ] == L'd';

				if ( to > from && !dots && !lone_void )
					count++;

				piece = at + 1;

				if ( c == L')' )
					break;

			}

		}

		return count;

	}

